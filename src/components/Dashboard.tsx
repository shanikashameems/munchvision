"use client";

import React, { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { DietaryAnalysis, FoodItem } from "@/src/types/food";
import { Sparkles, AlertTriangle, Edit2, Share2, Copy, Check } from "lucide-react";
import RefinePlate from "./RefinePlate";

interface DashboardProps {
  data: DietaryAnalysis;
  scannedImage?: string | null;
  onAdjustItem: (index: number, updated: FoodItem) => void;
}

export default function Dashboard({ data, scannedImage, onAdjustItem }: DashboardProps) {
  const [editingIndex, setEditingIndex] = useState<number | null>(null);
  const [copied, setCopied] = useState(false);

  // Targets for Ring Calculations (standard adult mid-range values)
  const targets = {
    protein: 100, // 100g
    carbs: 150,   // 150g
    fat: 70       // 70g
  };

  const pPercent = Math.min(1, data.totalProtein / targets.protein);
  const cPercent = Math.min(1, data.totalCarbs / targets.carbs);
  const fPercent = Math.min(1, data.totalFat / targets.fat);

  // SVG Concentric Ring Configurations
  // Center is (60, 60), size is 120
  const rings = [
    {
      label: "Protein",
      radius: 48,
      circ: 2 * Math.PI * 48, // ~301.6
      percent: pPercent,
      color: "text-blue-500 dark:text-blue-400",
      bgClass: "text-blue-500/10 dark:text-blue-400/10"
    },
    {
      label: "Carbs",
      radius: 37,
      circ: 2 * Math.PI * 37, // ~232.5
      percent: cPercent,
      color: "text-amber-500 dark:text-amber-400",
      bgClass: "text-amber-500/10 dark:text-amber-400/10"
    },
    {
      label: "Fats",
      radius: 26,
      circ: 2 * Math.PI * 26, // ~163.4
      percent: fPercent,
      color: "text-rose-500 dark:text-rose-400",
      bgClass: "text-rose-500/10 dark:text-rose-400/10"
    }
  ];

  const handleCopyReport = () => {
    const reportText = `MunchVision Plate Profile
------------------------------
Total Calories: ${data.totalCalories} kcal
Protein: ${data.totalProtein}g
Carbohydrates: ${data.totalCarbs}g
Fat: ${data.totalFat}g

Dietary Profile: ${data.dietaryFlags.join(", ")}
Health Insight: ${data.healthInsight}
${data.allergens.length > 0 ? `Allergen warning: ${data.allergens.join(", ")}` : ""}

Detected Items:
${data.itemsDetected.map(item => `- ${item.name} (${item.estimatedWeightGrams}g): ${item.calories} kcal (P: ${item.proteinGrams}g, C: ${item.carbsGrams}g, F: ${item.fatGrams}g)`).join("\n")}
------------------------------
Generated by MunchVision.`;

    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.6, ease: [0.16, 1, 0.3, 1] }}
      className="max-w-5xl mx-auto px-6 pb-24"
    >
      <div className="grid grid-cols-1 md:grid-cols-12 gap-8 items-start">
        
        {/* Left Column: Visual Assets (Image & SVG rings) */}
        <div className="md:col-span-5 space-y-6">
          
          {/* Main Visual Header (Frosted glass display) */}
          <div className="glass-panel rounded-3xl p-6 relative overflow-hidden flex flex-col items-center">
            <div className="absolute top-0 left-0 w-full h-1 bg-gradient-to-r from-blue-500 via-amber-500 to-rose-500" />
            
            {/* Visual Ring Chart */}
            <div className="relative w-48 h-48 flex items-center justify-center mb-4">
              <svg className="w-full h-full transform -rotate-90">
                {rings.map((ring, idx) => (
                  <g key={idx}>
                    {/* Ring track */}
                    <circle
                      cx="96"
                      cy="96"
                      r={ring.radius}
                      strokeWidth="6.5"
                      fill="transparent"
                      className={ring.bgClass}
                      stroke="currentColor"
                    />
                    {/* Active ring path */}
                    <motion.circle
                      cx="96"
                      cy="96"
                      r={ring.radius}
                      strokeWidth="6.5"
                      fill="transparent"
                      stroke="currentColor"
                      className={ring.color}
                      strokeDasharray={ring.circ}
                      initial={{ strokeDashoffset: ring.circ }}
                      animate={{ strokeDashoffset: ring.circ * (1 - ring.percent) }}
                      transition={{ duration: 1.2, ease: "easeOut" }}
                      strokeLinecap="round"
                    />
                  </g>
                ))}
              </svg>
              {/* Ring Center Labels */}
              <div className="absolute flex flex-col items-center text-center">
                <span className="text-4xl font-extrabold tracking-tighter text-neutral-900 dark:text-white">
                  {data.totalCalories}
                </span>
                <span className="text-[10px] uppercase font-bold tracking-widest text-neutral-400">
                  kcal
                </span>
              </div>
            </div>

            {/* Macro Labels grid */}
            <div className="grid grid-cols-3 gap-6 w-full text-center mt-2 border-t border-neutral-200/10 dark:border-neutral-800/10 pt-4">
              <div>
                <span className="inline-block w-2.5 h-2.5 rounded-full bg-blue-500 mr-1.5" />
                <span className="text-xs font-semibold text-neutral-400">Protein</span>
                <p className="text-sm font-bold mt-0.5">{data.totalProtein}g</p>
              </div>
              <div>
                <span className="inline-block w-2.5 h-2.5 rounded-full bg-amber-500 mr-1.5" />
                <span className="text-xs font-semibold text-neutral-400">Carbs</span>
                <p className="text-sm font-bold mt-0.5">{data.totalCarbs}g</p>
              </div>
              <div>
                <span className="inline-block w-2.5 h-2.5 rounded-full bg-rose-500 mr-1.5" />
                <span className="text-xs font-semibold text-neutral-400">Fat</span>
                <p className="text-sm font-bold mt-0.5">{data.totalFat}g</p>
              </div>
            </div>
          </div>

          {/* Scanned Image Preview */}
          {scannedImage && (
            <div className="glass-panel rounded-3xl p-3 relative overflow-hidden group shadow-md border border-neutral-200/20 dark:border-neutral-800/30">
              <span className="absolute top-4 left-4 z-10 px-2.5 py-1 text-[10px] font-bold bg-black/60 text-white rounded-full backdrop-blur-md">
                Captured Food
              </span>
              <img 
                src={scannedImage} 
                alt="Scanned Food Plate" 
                className="w-full aspect-[4/3] object-cover rounded-2xl grayscale-[20%] group-hover:grayscale-0 transition-all duration-500" 
              />
            </div>
          )}

          {/* Vibe Summary Tags */}
          <div className="flex flex-wrap gap-1.5 justify-start">
            {data.dietaryFlags.map((flag, idx) => (
              <span 
                key={idx} 
                className="px-3 py-1 rounded-full text-xs font-medium bg-neutral-200/30 dark:bg-neutral-800/40 text-neutral-700 dark:text-neutral-300 border border-neutral-200/10"
              >
                {flag}
              </span>
            ))}
          </div>

        </div>

        {/* Right Column: Nutrition Reports & Actions */}
        <div className="md:col-span-7 space-y-6">
          
          {/* Top Actions: Copy & Export */}
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-bold tracking-widest uppercase text-neutral-400 px-1">
              Plate Analysis
            </h3>
            
            <button
              onClick={handleCopyReport}
              className="flex items-center gap-1.5 px-3.5 h-8 rounded-full border border-neutral-200/40 dark:border-neutral-800/60 text-xs font-medium text-neutral-500 hover:text-neutral-900 dark:hover:text-white hover:bg-neutral-50 dark:hover:bg-neutral-900/60 transition-colors"
            >
              {copied ? (
                <>
                  <Check size={12} className="text-green-500" />
                  Copied Report
                </>
              ) : (
                <>
                  <Copy size={12} />
                  Copy Report
                </>
              )}
            </button>
          </div>

          {/* Custom Vision AI Insight */}
          <div className="glass-panel rounded-2xl p-5 bg-neutral-900/5 dark:bg-white/5 flex gap-4 items-start border border-neutral-200/10">
            <div className="p-2 rounded-xl bg-neutral-950 text-white dark:bg-white dark:text-black shrink-0">
              <Sparkles size={16} />
            </div>
            <div>
              <h4 className="text-xs font-bold uppercase tracking-wider text-neutral-400 mb-1">
                Vision Insight
              </h4>
              <p className="text-sm leading-relaxed text-neutral-700 dark:text-neutral-300 font-light">
                {data.healthInsight}
              </p>
            </div>
          </div>

          {/* Allergens Warning Panel */}
          {data.allergens.length > 0 && (
            <div className="glass-panel rounded-2xl p-5 border-rose-500/20 bg-rose-500/5 dark:bg-rose-500/10 flex gap-4 items-center">
              <div className="text-rose-500">
                <AlertTriangle size={20} />
              </div>
              <p className="text-xs font-medium text-rose-600 dark:text-rose-400">
                Potential Allergens Flagged:{" "}
                <span className="underline font-bold">{data.allergens.join(", ")}</span>
              </p>
            </div>
          )}

          {/* Items Detected Profile Section */}
          <div className="space-y-3">
            <h3 className="text-xs font-bold tracking-widest uppercase text-neutral-400 px-1">
              Detected Ingredients
            </h3>
            
            <div className="space-y-3">
              {data.itemsDetected.map((item, idx) => (
                <div key={idx} className="flex flex-col w-full">
                  <div className="glass-panel rounded-2xl p-4 flex items-center justify-between hover:bg-neutral-50 dark:hover:bg-neutral-900/30 transition-colors group">
                    <div>
                      <h4 className="text-sm font-semibold">{item.name}</h4>
                      <p className="text-xs text-neutral-400 mt-0.5">
                        Estimated Portion: {item.estimatedWeightGrams}g
                      </p>
                    </div>
                    <div className="flex items-center gap-4">
                      <div className="text-right text-xs">
                        <span className="font-bold text-neutral-800 dark:text-neutral-200">
                          {item.calories} kcal
                        </span>
                        <div className="flex gap-2 mt-0.5 font-light text-[10px] text-neutral-400">
                          <span>P: {item.proteinGrams}g</span>
                          <span>C: {item.carbsGrams}g</span>
                          <span>F: {item.fatGrams}g</span>
                        </div>
                      </div>
                      
                      <button 
                        onClick={() => setEditingIndex(editingIndex === idx ? null : idx)}
                        className={`p-2 rounded-full hover:bg-neutral-200 dark:hover:bg-neutral-800 transition-colors ${
                          editingIndex === idx ? "bg-neutral-200 dark:bg-neutral-800 text-neutral-900 dark:text-white" : "text-neutral-400"
                        }`}
                      >
                        <Edit2 size={12} />
                      </button>
                    </div>
                  </div>

                  <AnimatePresence>
                    {editingIndex === idx && (
                      <RefinePlate 
                        item={item} 
                        onSave={(updatedItem) => {
                          onAdjustItem(idx, updatedItem);
                          setEditingIndex(null);
                        }}
                        onCancel={() => setEditingIndex(null)}
                      />
                    )}
                  </AnimatePresence>
                </div>
              ))}
            </div>
          </div>

        </div>

      </div>
    </motion.div>
  );
}